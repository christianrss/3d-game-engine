//! Fonte bitmap procedural + atlas para HUD.

use crate::graphics::TextureData;

pub const GLYPH_W: u32 = 8;
pub const GLYPH_H: u32 = 12;
pub const GLYPH_COUNT: u32 = 96;
pub const ATLAS_W: u32 = GLYPH_W * 16;
pub const ATLAS_H: u32 = GLYPH_H * 6;

/// Gera atlas RGBA (branco = glyph) para ASCII 32..127.
pub fn build_font_atlas() -> TextureData {
    let mut pixels = vec![0u8; (ATLAS_W * ATLAS_H * 4) as usize];
    for (i, ch) in (32u8..128).enumerate() {
        let col = (i as u32) % 16;
        let row = (i as u32) / 16;
        let ox = col * GLYPH_W;
        let oy = row * GLYPH_H;
        raster_glyph(ch, &mut pixels, ox, oy);
    }
    TextureData {
        width: ATLAS_W,
        height: ATLAS_H,
        pixels,
    }
}

pub struct TextLayout {
    pub quads: Vec<TextQuad>,
}

#[derive(Clone, Copy)]
pub struct TextQuad {
    pub x: f32,
    pub y: f32,
    pub w: f32,
    pub h: f32,
    pub u0: f32,
    pub v0: f32,
    pub u1: f32,
    pub v1: f32,
}

impl TextLayout {
    pub fn measure(text: &str, px_size: f32) -> (f32, f32) {
        let scale = px_size / GLYPH_H as f32;
        let w = text.len() as f32 * GLYPH_W as f32 * scale;
        (w, px_size)
    }

    pub fn build(text: &str, x: f32, y: f32, px_size: f32) -> Self {
        let scale = px_size / GLYPH_H as f32;
        let mut quads = Vec::with_capacity(text.len());
        let mut cx = x;
        for ch in text.chars() {
            let idx = ch as u32;
            if idx < 32 || idx >= 128 {
                cx += GLYPH_W as f32 * scale;
                continue;
            }
            let gi = idx - 32;
            let col = gi % 16;
            let row = gi / 16;
            let u0 = (col * GLYPH_W) as f32 / ATLAS_W as f32;
            let v0 = (row * GLYPH_H) as f32 / ATLAS_H as f32;
            let u1 = u0 + GLYPH_W as f32 / ATLAS_W as f32;
            let v1 = v0 + GLYPH_H as f32 / ATLAS_H as f32;
            quads.push(TextQuad {
                x: cx,
                y,
                w: GLYPH_W as f32 * scale,
                h: px_size,
                u0,
                v0,
                u1,
                v1,
            });
            cx += GLYPH_W as f32 * scale;
        }
        Self { quads }
    }
}

fn raster_glyph(ch: u8, pixels: &mut [u8], ox: u32, oy: u32) {
    let rows = glyph_rows(ch);
    for (y, row) in rows.iter().enumerate() {
        for x in 0..GLYPH_W as usize {
            let on = (row >> (GLYPH_W as usize - 1 - x)) & 1 == 1;
            if !on {
                continue;
            }
            let px = ((oy + y as u32) * ATLAS_W + ox + x as u32) * 4;
            pixels[px as usize] = 255;
            pixels[px as usize + 1] = 255;
            pixels[px as usize + 2] = 255;
            pixels[px as usize + 3] = 255;
        }
    }
}

