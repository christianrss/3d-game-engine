fn rows(patterns: &[&str]) -> [u16; 12] {
    let mut out = [0u16; 12];
    for (i, line) in patterns.iter().enumerate() {
        out[i] = parse_row(line);
    }
    out
}

fn parse_row(s: &str) -> u16 {
    let mut v = 0u16;
    for (i, c) in s.chars().take(8).enumerate() {
        if c == '1' {
            v |= 1 << (7 - i);
        }
    }
    v
}

